// Writes src/iso.js: which ISO 3166-1 alpha-3 code belongs to each country on the map, from Natural Earth's
// admin-0 country table (public domain). The map's countries (world-atlas) carry the ISO numeric code as their id,
// and Natural Earth lists numeric and alpha-3 codes together (ISO_N3_EH / ISO_A3_EH, which fill in the codes
// France, Norway and others lack in the plain fields).
// Usage: node scripts/build_iso.js [path to ne_10m_admin_0_countries.geojson]   (downloads it when no path is given)
// The output is committed, so builds and the editor need neither Natural Earth's country table nor the network.
const fs = require('fs'),
  path = require('path');
const URL = 'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_10m_admin_0_countries.geojson';

// Parts the build splits out of France and the Netherlands (src/overseas.js). Natural Earth keeps them inside the
// parent, so their codes are added here; the Caribbean Netherlands is three places with one code each (BES), which
// statistics do not usually list.
const OVERSEAS = { GUF: '254', GLP: '312', MTQ: '474', REU: '638', MYT: '175', BES: '535' };
// Not in Natural Earth's table with a code: the World Bank's code for Kosovo. Matched by the map's name.
const BY_NAME = { XKX: 'Kosovo' };
// world-atlas gives Ashmore and Cartier Is. Australia's numeric id; it is a territory of Australia, not Australia
const SKIP = ['Ashmore and Cartier Is.'];

(async () => {
  const file = process.argv[2];
  const j = file ? JSON.parse(fs.readFileSync(file, 'utf8')) : await (await fetch(URL)).json();
  const atlas = require('world-atlas/countries-10m.json').objects.countries.geometries;
  const ids = new Set(atlas.filter((g) => g.id).map((g) => g.id));
  const rows = j.features.map((f) => f.properties);
  const out = {};
  for (const id of [...ids].sort()) {
    const cand = rows.filter((p) => String(p.ISO_N3_EH).padStart(3, '0') === id && /^[A-Z]{3}$/.test(p.ISO_A3_EH));
    // the row for the country itself, not for a far-off territory that shares its code (Clipperton, Brazilian I.)
    const p = cand.find((c) => c.ADM0_A3 === c.ISO_A3_EH) || cand[0];
    if (!p) throw new Error('no ISO alpha-3 code for numeric id ' + id);
    out[p.ISO_A3_EH] = id;
  }
  Object.assign(out, OVERSEAS);
  const keys = Object.keys(out).sort();
  const src =
    "// ISO 3166-1 alpha-3 code -> the map country's id (its ISO numeric code), from Natural Earth's admin-0 country table.\n" +
    '// Generated by scripts/build_iso.js; do not edit. Used to match statistics (src/js/stats.js) to countries.\n' +
    'const ISO3_ID = {\n' +
    keys.map((k) => '  ' + k + ": '" + out[k] + "',").join('\n') +
    '\n};\n' +
    "// Codes matched by the map's country name (no numeric id).\n" +
    'const ISO3_NAME = ' +
    JSON.stringify(BY_NAME) +
    ';\n' +
    "// Map places that share another place's numeric id and take no code of their own.\n" +
    'const ISO_SKIP = ' +
    JSON.stringify(SKIP) +
    ';\n' +
    'module.exports = { ISO3_ID, ISO3_NAME, ISO_SKIP };\n';
  fs.writeFileSync(path.join(__dirname, '..', 'src', 'iso.js'), src);
  console.log('wrote src/iso.js:', keys.length, 'codes');
})().catch((e) => {
  console.error(e.message);
  process.exit(1);
});
